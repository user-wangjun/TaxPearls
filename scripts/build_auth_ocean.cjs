/* Rebuild after editing auth-ocean.mjs or the vendored Three.js module:
 *   node scripts/build_auth_ocean.cjs
 * Verification needs only Node: node scripts/build_auth_ocean.cjs --check
 * The generated module is committed with the source; the Python server needs
 * no Node installation or build step at runtime.
 */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');
const zlib = require('zlib');
const os = require('os');
const {execSync} = require('child_process');
const root = path.resolve(__dirname, '..');
const output = path.join(root, 'webapp/static/auth-ocean.bundle.mjs');
// Pin the builder so rebuilding does not silently pick a different optimizer.
const buildCommand = 'npx --yes esbuild@0.28.1 --sourcefile=auth-ocean.mjs --bundle --minify --format=esm --target=es2020 --legal-comments=inline --log-level=warning';
function oceanVendor(vendor, ocean) {
  // This private bundle exports only mountOcean. Its scenes use custom
  // ShaderMaterial programs, so standard material shaders never run here.
  // Keep the complete vendored module intact for every other consumer.
  const chunks = ['common', 'colorspace_fragment', 'colorspace_pars_fragment', 'tonemapping_pars_fragment'];
  const materials = [...ocean.matchAll(/new\s+THREE\.(\w+Material)\b/g)].map(match => match[1]);
  const includes = [...ocean.matchAll(/#include\s*<([\w]+)>/g)].map(match => match[1]);
  if (!materials.length || materials.some(name => name !== 'ShaderMaterial') ||
      includes.some(name => !chunks.includes(name)) ||
      !/renderer\.toneMapping\s*=\s*THREE\.NoToneMapping\b/.test(ocean) ||
      /\.(?:background|environment)\s*=|\.shadowMap\s*\./.test(ocean)) {
    throw new Error('Ocean shader features changed; review its scoped Three.js shader tables before rebuilding.');
  }
  let chunkTables = 0, shaderTables = 0;
  const scoped = vendor.replace(/const ShaderChunk = \{[\s\S]*?\n\};/, () => {
    chunkTables++;
    return 'const ShaderChunk = {' + chunks.join(', ') + '};';
  }).replace(/const ShaderLib = \{[\s\S]*?\n\};\s*ShaderLib\.physical = \{[\s\S]*?\n\};/, () => {
    shaderTables++;
    return 'const ShaderLib = {};';
  });
  if (chunkTables !== 1 || shaderTables !== 1) throw new Error('Unexpected vendored Three.js shader tables.');
  return scoped;
}
function sourceStamp() {
  const hash = crypto.createHash('sha256');
  for (const file of ['scripts/build_auth_ocean.cjs', 'webapp/static/auth-ocean.mjs', 'webapp/static/vendor/three.module.mjs']) {
    hash.update(file + '\0');
    hash.update(fs.readFileSync(path.join(root, file), 'utf8').replace(/\r\n/g, '\n'));
    hash.update('\0');
  }
  return '// Generated by scripts/build_auth_ocean.cjs; source-sha256=' + hash.digest('hex') + '\n';
}
function assertCurrent() {
  if (!fs.existsSync(output) || !fs.readFileSync(output, 'utf8').startsWith(sourceStamp())) {
    throw new Error('Ocean bundle is missing or stale. Run node scripts/build_auth_ocean.cjs');
  }
  const compressed = output + '.br';
  if (!fs.existsSync(compressed) || !zlib.brotliDecompressSync(fs.readFileSync(compressed)).equals(fs.readFileSync(output))) {
    throw new Error('Compressed ocean bundle is missing or stale. Run node scripts/build_auth_ocean.cjs');
  }
}
if (require.main === module) {
  if (process.argv.includes('--check')) {
    assertCurrent();
    console.log('Ocean bundle matches its source and pinned build settings.');
  } else {
    const source = fs.readFileSync(path.join(root, 'webapp/static/auth-ocean.mjs'), 'utf8');
    const marker = "from './vendor/three.module.mjs'";
    if (!source.includes(marker)) throw new Error('Unexpected ocean vendor import.');
    const vendor = oceanVendor(fs.readFileSync(path.join(root, 'webapp/static/vendor/three.module.mjs'), 'utf8'), source);
    const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'taxpearls-ocean-'));
    const temporaryVendor = path.join(temporary, 'three.ocean.mjs');
    let code;
    try {
      fs.writeFileSync(temporaryVendor, vendor);
      code = execSync(buildCommand, {cwd: temporary, input: source.replace(marker, "from './three.ocean.mjs'"),
        maxBuffer: 8 * 1024 * 1024, stdio: ['pipe', 'pipe', 'inherit']});
    } finally {
      if (fs.existsSync(temporaryVendor)) fs.unlinkSync(temporaryVendor);
      fs.rmdirSync(temporary);
    }
    fs.writeFileSync(output, Buffer.concat([Buffer.from(sourceStamp()), code]));
    fs.writeFileSync(output + '.br', zlib.brotliCompressSync(fs.readFileSync(output), {params: {
      [zlib.constants.BROTLI_PARAM_QUALITY]: 11,
      [zlib.constants.BROTLI_PARAM_MODE]: zlib.constants.BROTLI_MODE_TEXT,
    }}));
    console.log('Built webapp/static/auth-ocean.bundle.mjs (' + fs.statSync(output).size + ' bytes).');
  }
}
module.exports = {assertCurrent, oceanVendor};
