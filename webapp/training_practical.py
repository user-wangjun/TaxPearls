def items_for(chapter_codes: list[str]) -> list[dict[str, Any]]:
    """按证书实际存在的章节编码取实操清单；没有对应编码的章节静默跳过。"""
    known = set(chapter_codes)
    out: list[dict[str, Any]] = []
    for code in chapter_codes:
        if code not in known or code not in CHAPTER_PRACTICAL:
            continue
        for order, item in enumerate(CHAPTER_PRACTICAL[code], start=1):
            out.append({
                "id": f"{code}-P{order}",
                "chapter_code": code,
                "title": item["title"],
                "steps": list(item["steps"]),
                "deliverable": item["deliverable"],
                "focus_codes": list(item.get("focus_codes") or []),
                "source": VERSION,
            })
    return out


def coverage(chapter_codes: list[str]) -> dict[str, Any]:
    """清单覆盖情况：用于详情页如实说明"哪些章节有实操建议、哪些还没有"。"""
    codes = [c for c in chapter_codes if c in CHAPTER_PRACTICAL]
    return {"version": VERSION, "source_note": SOURCE_NOTE,
            "chapters_with_items": len(codes), "chapters_total": len(chapter_codes)}
